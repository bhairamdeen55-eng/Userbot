# ────────────────────────────────────────────────
#   OPT-IN GROUP FUN BOT v2.4 (Telethon Userbot)
#   Text replies remain opt-in/consent-based. Reactions
#   in groups are NOT consent-gated (see v2.4 note below) —
#   this raises automation-detection / ban risk, use with care.
#
#   CHANGES IN v2.4:
#   - Group reactions ab SABHI messages pe chalti hain, opt-in
#     ki zaroorat nahi (pehle sirf opted-in members ke messages
#     pe reaction milti thi). Text-reply abhi bhi sirf opted-in
#     members ke liye hai — sirf reaction ka scope badla hai.
#   - Reaction ka apna alag per-user cooldown hai (chat ke
#     `.funcooldown` wahi cooldown reuse karta hai) taaki har
#     single message pe reaction dene se flood/ban risk na badhe.
#   - `.funreact on/off` ab is naye "react-to-everyone" behaviour
#     ko bhi control karta hai.
#
#   CHANGES IN v2.3:
#   - Bot ab HAR reply pe TEXT + REAL Telegram REACTION
#     dono ek saath deta hai — group aur DM, dono jagah,
#     hamesha (pehle wala 25% random "bonus" hata diya)
#   - Reaction ab asli Telegram reaction hai (SendReactionRequest
#     se), pehle wo sirf ek extra text message tha jo dikhta
#     reaction jaisa tha lekin actually reaction nahi tha
#   - `.funreact on/off` command ab kaam karta hai (pehle sirf
#     changelog me likha tha, code me implement nahi tha)
#   - DMs me reactions hamesha allowed hain (jaisa comment me
#     pehle se likha tha)
#
#   CHANGES IN v2.2:
#   - Bot ab HAR baar TEXT reply + emoji REACTION dono
#     ek saath deta hai — group aur DM, dono jagah
#   - New admin command `.funreact on/off` to toggle
#     reactions per group (DMs always allowed to react)
#
#   CHANGES IN v2.1:
#   - All auto-replies trimmed to 2-4 words (short & punchy)
#   - Fixed opt-out bug: leaving now saves the member's
#     history to an audit log BEFORE deleting the active
#     record, instead of losing it
#   - Everything else from v2 kept (cooldowns, quiet hours,
#     triggers, moods, broadcast, export, kill-switch, etc.)
#
#   NOTE: This is a userbot (runs on a personal account via
#   Telethon), not a Bot API bot. Automating a personal
#   Telegram account like this can conflict with Telegram's
#   Terms of Service (which restrict bulk/automated messaging
#   from user accounts) and can get the account limited or
#   banned, regardless of how consent-based the feature is.
#   Worth keeping in mind before running this on a real account.
# ────────────────────────────────────────────────

